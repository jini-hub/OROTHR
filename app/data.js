export const uid = () => (globalThis.crypto?.randomUUID?.() || `orot-${Date.now()}-${Math.random().toString(36).slice(2)}`);
export function createWorkspace() {
  const now = new Date().toISOString();
  const stages = SEED.stageDefs.map((s, i) => ({id:`stage-${i+1}`,name:s[0],description:s[1]}));
  const tasks = SEED.tasks.map((t, i) => ({
    id: uid(), stageId:stages[t.stageIndex].id, title:t.title, purpose:t.purpose, prepare:t.prepare, steps:t.steps.join('\n'), outputs:t.outputs, criteria:t.criteria,
    status:'not_started', due:'', important:false, memo:'', updatedAt:now,
    groups:t.groups.map(g=>({id:uid(),title:g[0],items:g[1].map((item)=>({
      id:uid(),title:item,guide:'',done:false,na:false,naReason:'',availability:'unknown',obtained:'unknown',owner:'',location:'',referenceDate:'',result:'',followUp:'',link:'',doneAt:null,updatedAt:now
    }))}))
  }));
  return {schemaVersion:1,name:'나의 HR 구축 작업공간',goalDays:90,createdAt:now,updatedAt:now,stages,tasks,trash:[],activity:[]};
}
export const STATUSES = {not_started:'미착수', in_progress:'진행 중', waiting:'대기', complete:'완료', not_applicable:'해당 없음'};
export function getStageProgress(ws, stageId) {
 const active=ws.tasks.filter(t=>t.stageId===stageId&&t.status!=='not_applicable');
 return {total:active.length,done:active.filter(t=>t.status==='complete').length,percent:active.length?Math.round(active.filter(t=>t.status==='complete').length/active.length*100):null};
}
export function getTaskProgress(task) {
 const list=task.groups.flatMap(g=>g.items).filter(i=>!i.na);
 return {total:list.length,done:list.filter(i=>i.done).length,percent:list.length?Math.round(list.filter(i=>i.done).length/list.length*100):null};
}
